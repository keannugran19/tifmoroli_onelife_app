B. The Nature of the Resurrection.
The Resurrection will be universal. All do not have eternal life, but all have eternal existence. All persons will be resurrected, the just to eternal life, the unjust to eternal condemnation. All will be raised, but not all at the same time (Jn 5:28, 29).

Jn 5:28, 29,28 “Do not be amazed at this, for a time is coming when all who are in their graves will hear his voice 29 and come out—those who have done what is good will rise to live, and those who have done what is evil will rise to be condemned.

1. The Resurrection of Believers (1 Thes 4:13-18; 1 Cor 15:50-57; Rv. 20: 4-6).
The Resurrection of the Church occurs at the Coming of Jesus, immediately prior to the Rapture (1 Thes 4:16). The Believers’ Resurrection is called the “first resurrection”: “Blessed and holy is he that hath part in the first resurrection: on such the second death hath no power…” (Rv. 20:6). It has been taught by some that there will be one general resurrection of the dead and one judgment at which just and unjust are judged. Jesus sometimes mentioned the two resurrections and judgments in the same passage, but a careful reading will reveal that Jesus was not speaking of one general resurrection: “And shall come forth; they that have done good unto the resurrection of life; and they that have done evil unto the resurrection of damnation; (Jn 5:29). Notice that one is a resurrection of life while other is a resurrection of condemnation; they are not the same, nor do they occur at the same time, as Paul and John both elucidate.
It is normal for prophetic perspective to view several related future events as if they were one event. With similar prophetic language, the first and second comings of Jesus are merged in the same passage in Old Testament prophecy (Is 9:6,7; 61:1-3; Dn 12:2). New Testament writers sometimes allude to both the Rapture and Final Coming in the same reference (1Thes 3:13). Both Paul and John make I clear that the Saint’s Resurrection (including the saved remnant of Israel and the Tribulation saints) takes place at Christ’s Coming and before the Millennial Reign (1 Cor 15:51, 52; Rv. 20:4-6; Dan 12:1-2).
That the Saint’s Resurrection is selective is seen in a remarkable statement of the Apostle Paul: “that I may know Him, and the power of His resurrection, and the fellowship of His sufferings, being made conformable unto His death; if by any means I might attain unto the resurrection of dead” (Phil 3:10,11). If there is only one general resurrection for the just and the unjust, would Paul aspire to attain to it? A more literal translation reveals Paul’s full meaning: “… If by any means I might advance to the EARLIER resurrection, which is FROM AMONG the dead” (Phil 3:11, Rotherham). The Greek preposition ek means “out from,” Paul desired to be in the group that would be resurrected at the time of the Rapture; those who would be taken selectively “out from among “ the general mass of the dead; those who would be raised in the EARLIER resurrection (the first resurrection, Rv 20:6). The Greek word for “resurrection”; the double use of the word ek gives added emphasis to the idea that the Resurrection of the Christian believers is one in which they selected for a special awakening. That there will be several orders of resurrection is expressed in another place by Paul: “But every man in his own order: Christ the firstfruits; afterward they that are Christ’s at His coming” (1Cor 15:23).


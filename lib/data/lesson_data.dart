C. The Time of the Resurrection.
The order of resurrections is as follows:

1. The Resurrection of Jesus (Mt 28:1-10; Mk 16:1-14; Lk. 24:1-39; Jn 20:1-17).

2. A Resurrection of saints of the Old Testament (Mt. 27:52, 53).

3. The Resurrection of the Church saints at the Rapture (Jn 14:3; 1 Thes 4:16, 1 Cor 15:52).

4. The Resurrection of the two witnesses of Revelation 11:12, during the tribulation period.

5. The Resurrection of the saints of Israel and of the Tribulation saints who are witnesses for Christ and who do not worship the Beast (Rv. 20:4-6; Dn 12:1,2).

6. The Resurrection of the unrighteous.
This will occur after the Millennial Reign of Christ. They will be resurrected to stand before the Great White Throne (Rv 20:5,11-14).
